-- Runs once per environment. &{ENV} becomes DEV or TEST.

CREATE DATABASE IF NOT EXISTS FBL_POLICY_&{ENV};
CREATE SCHEMA IF NOT EXISTS FBL_POLICY_&{ENV}.APP;

CREATE TABLE IF NOT EXISTS FBL_POLICY_&{ENV}.APP.POLICY (
    POLICY_ID   NUMBER,
    HOLDER_NAME VARCHAR,
    PREMIUM_AMT NUMBER(12,2)
);

CREATE OR REPLACE VIEW FBL_POLICY_&{ENV}.APP.POLICY_V1 AS
SELECT POLICY_ID, HOLDER_NAME, PREMIUM_AMT
FROM FBL_POLICY_&{ENV}.APP.POLICY;


